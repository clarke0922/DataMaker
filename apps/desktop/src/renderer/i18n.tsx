function format(message: string, params?: Params) {
  return params
    ? message.replace(/\{(\w+)\}/g, (_, key: string) =>
        String(params[key] ?? `{${key}}`),
      )
    : message;
}

type I18nValue = {
  locale: Locale;
  setLocale(locale: Locale): void;
  t(key: string, params?: Params): string;
};
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() =>
    localStorage.getItem("datamaker.locale") === "zh-CN" ? "zh-CN" : "en-US",
  );
  const value = useMemo<I18nValue>(
    () => ({
      locale,
      setLocale(next) {
        localStorage.setItem("datamaker.locale", next);
        setLocaleState(next);
      },
      t(key, params) {
        return format(locale === "zh-CN" ? (zh[key] ?? key) : key, params);
      },
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
